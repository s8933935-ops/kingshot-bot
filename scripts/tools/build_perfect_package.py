# 統計計算とタイムコード割り振り
# セリフ文字数に応じて自然な秒数を配分（平均約9.2文字/秒 + 間0.4秒）
total_chars = 0
timeline_data = []
current_time = 0.0

for cut_id, char, code, line, telop, prompt in cuts_data:
    n_chars = len(line)
    total_chars += n_chars
    # 秒数計算: 文字数 / 9.2 + 0.5秒の自然な間
    duration = max(4.0, round(n_chars / 9.2 + 0.5, 1))
    start_time = current_time
    end_time = round(start_time + duration, 1)
    current_time = end_time
    timeline_data.append((cut_id, char, code, start_time, end_time, line, telop, prompt))

total_seconds = current_time
total_minutes = total_seconds / 60.0

